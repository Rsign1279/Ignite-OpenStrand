export const stages = [
  "PROFILE",
  "READY",
  "PRE_QUESTION",
  "PRE_RECORDING",
  "PRE_PROCESSING",
  "PRE_RESULTS",
  "STAR_LESSON",
  "POST_READY",
  "POST_QUESTION",
  "POST_RECORDING",
  "POST_PROCESSING",
  "POST_COMPARISON",
  "TRANSFER_QUESTION",
  "TRANSFER_RECORDING",
  "TRANSFER_PROCESSING",
  "TRANSFER_RESULTS",
  "COMPLETE",
] as const;
export type Stage = (typeof stages)[number];
const transitions: Record<Stage, readonly Stage[]> = {
  PROFILE: ["READY"],
  READY: ["PRE_QUESTION"],
  PRE_QUESTION: ["PRE_RECORDING", "PRE_PROCESSING"],
  PRE_RECORDING: ["PRE_PROCESSING", "PRE_QUESTION"],
  PRE_PROCESSING: ["PRE_RESULTS", "PRE_QUESTION"],
  PRE_RESULTS: ["STAR_LESSON"],
  STAR_LESSON: ["POST_READY"],
  POST_READY: ["POST_QUESTION"],
  POST_QUESTION: ["POST_RECORDING", "POST_PROCESSING"],
  POST_RECORDING: ["POST_PROCESSING", "POST_QUESTION"],
  POST_PROCESSING: ["POST_COMPARISON", "POST_QUESTION"],
  POST_COMPARISON: ["TRANSFER_QUESTION"],
  TRANSFER_QUESTION: ["TRANSFER_RECORDING", "TRANSFER_PROCESSING"],
  TRANSFER_RECORDING: ["TRANSFER_PROCESSING", "TRANSFER_QUESTION"],
  TRANSFER_PROCESSING: ["TRANSFER_RESULTS", "TRANSFER_QUESTION"],
  TRANSFER_RESULTS: ["COMPLETE"],
  COMPLETE: ["READY"],
};
export function transition(stage: Stage, next: Stage) {
  if (!transitions[stage].includes(next))
    throw new Error(`Invalid transition ${stage} -> ${next}`);
  return next;
}
